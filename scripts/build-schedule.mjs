#!/usr/bin/env node
// Builds/extends data/schedule.js — the append-only, precomputed daily-answer
// order. Never hand-edit data/schedule.js's `order` array directly; re-run
// this script instead.
//
// - First run (no existing schedule.js, or --init): shuffles every eligible
//   mic id (needsVerification !== true) with a fixed-seed deterministic
//   shuffle and writes the initial order.
// - Later runs: only shuffles and APPENDS ids that aren't already in
//   `order` (i.e. new mics added to data/mics.js since the last run).
//   Existing indices are never touched, which is what keeps past days'
//   answers stable as the pool grows.
//
// Usage: node scripts/build-schedule.mjs [--launch-date=YYYY-MM-DD]

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const micsPath = join(root, "data", "mics.js");
const schedulePath = join(root, "data", "schedule.js");

function loadMicIds() {
  const src = readFileSync(micsPath, "utf8");
  const sandbox = { module: { exports: {} } };
  const fn = new Function("module", "exports", src + "\n;module.exports = { MIC_DB };");
  fn(sandbox.module, sandbox.module.exports);
  const { MIC_DB } = sandbox.module.exports;
  return MIC_DB.filter((m) => m.needsVerification !== true).map((m) => m.id);
}

function loadExistingSchedule() {
  if (!existsSync(schedulePath)) return null;
  const src = readFileSync(schedulePath, "utf8");
  const sandbox = { module: { exports: {} } };
  const fn = new Function("module", "exports", src + "\n;module.exports = { SCHEDULE };");
  fn(sandbox.module, sandbox.module.exports);
  return sandbox.module.exports.SCHEDULE;
}

// mulberry32 — small deterministic PRNG, fixed seed for reproducibility.
function mulberry32(seed) {
  let a = seed;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const SEED = 0x4d494347; // "MICG" — fixed, arbitrary, never change once shipped

function seededShuffle(arr, rng) {
  const out = [...arr];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

function main() {
  const launchDateArg = process.argv.find((a) => a.startsWith("--launch-date="));
  const eligibleIds = loadMicIds();
  const existing = loadExistingSchedule();
  const rng = mulberry32(SEED);

  let launchDate, order;

  if (!existing) {
    launchDate = launchDateArg ? launchDateArg.split("=")[1] : new Date().toISOString().slice(0, 10);
    order = seededShuffle(eligibleIds, rng);
    console.log(`Initializing schedule: ${order.length} mics, launch date ${launchDate}`);
  } else {
    launchDate = existing.launchDate;
    const already = new Set(existing.order);
    const newIds = eligibleIds.filter((id) => !already.has(id));
    if (newIds.length === 0) {
      console.log("No new eligible mics to append. Schedule unchanged.");
      return;
    }
    const shuffledNew = seededShuffle(newIds, rng);
    order = [...existing.order, ...shuffledNew];
    console.log(`Appending ${shuffledNew.length} new mic(s) to schedule (was ${existing.order.length}, now ${order.length}).`);
  }

  const body = `// GENERATED by scripts/build-schedule.mjs — do not hand-edit \`order\`.
// One mic id per calendar day, starting at launchDate. Append-only: new mics
// are always shuffled and added to the END so past days' answers never change.
const SCHEDULE = {
  launchDate: ${JSON.stringify(launchDate)},
  order: ${JSON.stringify(order, null, 2)}
};
if (typeof module !== "undefined") module.exports = { SCHEDULE };
`;
  writeFileSync(schedulePath, body);
  console.log(`Wrote ${schedulePath}`);
}

main();
